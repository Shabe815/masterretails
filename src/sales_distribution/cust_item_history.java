	static void  get_po_disp( String company, String cust, String search)
	{
		String serch_str = "";
		if(!search.equals(""))
		{
			serch_str="and (ref_cust_id LIKE '%"+search+"%' OR ref_itemcode LIKE '%"+search+"%' OR item_name LIKE '%"+search+"%' OR barcode = '"+search+"' ) ";
		
		}
		try{
			Connection con=Dbsetup.dbconn.getConnection();
			Statement statement=con.createStatement();  
			String query="SELECT * FROM "+company+".mr_customer_items inner join "+company+".mr_item_master on mr_item_master.item_code=mr_customer_items.ref_itemcode  where mr_customer_items.ref_cust_id='"+cust+"' "+serch_str+" "; 
			ResultSet resultSet = statement.executeQuery(query);
			int rowCount = model.getRowCount();
			for (int i = rowCount - 1; i >= 0; i--) {
				model.removeRow(i);
			}
			if(resultSet.next())
			{
				String query1="SELECT * FROM "+company+".mr_customer_items inner join "+company+".mr_item_master on mr_item_master.item_code=mr_customer_items.ref_itemcode  where mr_customer_items.ref_cust_id='"+cust+"' "+serch_str+" "; 
				ResultSet resultSet1 = statement.executeQuery(query1);
				while(resultSet1.next())
				{
					String ref_itemcode=resultSet1.getString("ref_itemcode");
	                String item_name=resultSet1.getString("item_name");
	                String unit=resultSet1.getString("unit");
	                String price=resultSet1.getString("price");
	                String modified_date=resultSet1.getString("modified_date");
	                String invoice_num = resultSet1.getString("invoice_num");
	                model.addRow(new Object[]{invoice_num,ref_itemcode,item_name,unit,price,modified_date});
				}
			}
			else
			{
				JOptionPane.showMessageDialog(frame, "No Items List Found");
	        	for (int i = model.getRowCount() - 1; i >= 0; i--) {
	        	    model.removeRow(i);
	        	}
			}
			con.close();
		}
		catch(Exception e){
			System.err.println(e);
		}
	}
